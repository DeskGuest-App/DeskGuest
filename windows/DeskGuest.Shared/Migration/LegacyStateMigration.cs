namespace DeskGuest.Shared.Migration;

/// <summary>ACP → DeskGuest rename (BUILD-PROGRAMME item 20): one-time
/// state carry-over. The product's data root moved from
/// %ProgramData%\ACP\data to %ProgramData%\DeskGuest\data. On first
/// start under the new identity the legacy tree is COPIED (never
/// moved — the legacy tree is left untouched for rollback) into the
/// new root and a marker file records the migration.
///
/// This helper is the SINGLE named place in the shipped product
/// that references the legacy path, and it exists only to move the
/// owner's existing state once, at the R1 deploy. It is not a
/// recognition/match string: nothing protective keys off the old
/// name. Idempotent: the marker makes every later run a no-op.
///
/// TWO MODES (R1 fix, 2026-11-26): the original contract copied
/// only into an ABSENT/EMPTY new tree and treated any populated
/// new tree as "already migrated, leave untouched" — which the
/// R1 installer defeated by seeding the new tree (identity, terms
/// receipt, role, slot binaries) BEFORE the first Core start, so
/// the carry-over silently never ran and the owner's pairings,
/// trust and history stayed behind. A populated new tree now
/// MERGES: every legacy file whose destination is absent is
/// copied; an existing destination file is NEVER overwritten
/// (the live install's own state wins every conflict). The
/// marker is written in both modes with a full reconciliation —
/// filesCopied + filesAlreadyPresent + filesExcluded always
/// equals the legacy file total at migration time, so a carry
/// can be audited against the legacy tree as it stood.
///
/// EXCLUDED BY RULE in both modes (machine-local machinery, not
/// owner state): the updates\ subtree (A/B slot binaries and the
/// update pointer — the new install's own seeded slots govern),
/// the staging\ subtree (transient transfer staging), root-level
/// liveness files (heartbeat.json, run-marker.json,
/// run-marker.stale-*.json — regenerated by the running Core,
/// never carried as claims), core-instance.lock, and the marker
/// file itself. Removable in the release after the R1 deploy
/// verifies the carry-over on the owner's machine.</summary>
public static class LegacyStateMigration
{
    public const string MarkerFileName = "deskguest-migration.json";

    public enum Outcome { Migrated, Merged, AlreadyMigrated, NoLegacyTree }

    public sealed record Result(Outcome Outcome, int FilesCopied, int FilesAlreadyPresent,
        int FilesExcluded, string? Detail);

    /// <summary>The legacy data dir this helper migrates FROM.
    /// Windows: %ProgramData%\ACP\data. Non-Windows: the legacy
    /// sibling "acp-data" next to the install (the Linux build VM's
    /// console-host layout).</summary>
    public static string DefaultLegacyDataDir(string installBaseDir)
        => OperatingSystem.IsWindows()
            ? Path.Combine(
                Environment.GetFolderPath(Environment.SpecialFolder.CommonApplicationData),
                "ACP", "data")
            : Path.Combine(installBaseDir, "acp-data");

    /// <summary>True when a legacy file (by its path relative to
    /// the legacy data root) is machine-local machinery the
    /// carry-over must never move — see the class doc.</summary>
    public static bool IsExcluded(string relativePath)
    {
        var parts = relativePath.Split(
            new[] { Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar },
            StringSplitOptions.RemoveEmptyEntries);
        if (parts.Length == 0) return true;
        if (parts.Length > 1 &&
            (parts[0].Equals("updates", StringComparison.OrdinalIgnoreCase)
             || parts[0].Equals("staging", StringComparison.OrdinalIgnoreCase)))
            return true;
        if (parts.Length == 1)
        {
            var name = parts[0];
            if (name.Equals(MarkerFileName, StringComparison.OrdinalIgnoreCase)
                || name.Equals("heartbeat.json", StringComparison.OrdinalIgnoreCase)
                || name.Equals("run-marker.json", StringComparison.OrdinalIgnoreCase)
                || name.Equals("core-instance.lock", StringComparison.OrdinalIgnoreCase))
                return true;
            if (name.StartsWith("run-marker.stale-", StringComparison.OrdinalIgnoreCase)
                && name.EndsWith(".json", StringComparison.OrdinalIgnoreCase))
                return true;
        }
        return false;
    }

    public static Result EnsureMigrated(string newDataDir, string legacyDataDir)
    {
        if (File.Exists(Path.Combine(newDataDir, MarkerFileName)))
            return new Result(Outcome.AlreadyMigrated, 0, 0, 0, "marker present");
        if (!Directory.Exists(legacyDataDir))
            return new Result(Outcome.NoLegacyTree, 0, 0, 0, "no legacy tree to carry over");

        var newTreePopulated = Directory.Exists(newDataDir)
            && Directory.EnumerateFileSystemEntries(newDataDir).Any();

        var copied = 0;
        var present = 0;
        var excluded = 0;
        foreach (var src in Directory.EnumerateFiles(legacyDataDir, "*", SearchOption.AllDirectories))
        {
            var rel = Path.GetRelativePath(legacyDataDir, src);
            if (IsExcluded(rel)) { excluded++; continue; }
            var dst = Path.Combine(newDataDir, rel);
            if (File.Exists(dst)) { present++; continue; }
            Directory.CreateDirectory(Path.GetDirectoryName(dst)!);
            File.Copy(src, dst, overwrite: false);
            copied++;
        }
        // Empty legacy directories are part of the state shape too
        // (the excluded machinery subtrees are not recreated).
        foreach (var dir in Directory.EnumerateDirectories(legacyDataDir, "*", SearchOption.AllDirectories))
        {
            var rel = Path.GetRelativePath(legacyDataDir, dir);
            var first = rel.Split(
                new[] { Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar },
                StringSplitOptions.RemoveEmptyEntries).FirstOrDefault() ?? "";
            if (first.Equals("updates", StringComparison.OrdinalIgnoreCase)
                || first.Equals("staging", StringComparison.OrdinalIgnoreCase))
                continue;
            Directory.CreateDirectory(Path.Combine(newDataDir, rel));
        }
        Directory.CreateDirectory(newDataDir);
        File.WriteAllText(Path.Combine(newDataDir, MarkerFileName),
            "{\n" +
            $"  \"migratedFrom\": {System.Text.Json.JsonSerializer.Serialize(legacyDataDir)},\n" +
            $"  \"migratedAtUtc\": \"{DateTimeOffset.UtcNow:O}\",\n" +
            $"  \"mode\": \"{(newTreePopulated ? "merge" : "copy")}\",\n" +
            $"  \"filesCopied\": {copied},\n" +
            $"  \"filesAlreadyPresent\": {present},\n" +
            $"  \"filesExcluded\": {excluded},\n" +
            $"  \"legacyFilesTotal\": {copied + present + excluded}\n" +
            "}\n");
        return new Result(
            newTreePopulated ? Outcome.Merged : Outcome.Migrated,
            copied, present, excluded, null);
    }
}
